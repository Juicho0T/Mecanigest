CREATE TABLE IF NOT EXISTS usuarios (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL, correo VARCHAR(190) NOT NULL UNIQUE,
 clave_hash VARCHAR(255) NOT NULL,
 rol ENUM('administrador','recepcionista','mecanico') NOT NULL,
 activo TINYINT(1) NOT NULL DEFAULT 1,
 creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS clientes (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(120) NOT NULL,
 telefono VARCHAR(25) NOT NULL, correo VARCHAR(190) NOT NULL DEFAULT '', direccion VARCHAR(250) NOT NULL DEFAULT '',
 activo TINYINT(1) NOT NULL DEFAULT 1, creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(nombre), INDEX(telefono)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS vehiculos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cliente_id INT UNSIGNED NOT NULL,
 marca VARCHAR(60) NOT NULL, modelo VARCHAR(80) NOT NULL, anio SMALLINT UNSIGNED NOT NULL,
 placas VARCHAR(20) NOT NULL UNIQUE, activo TINYINT(1) NOT NULL DEFAULT 1,
 FOREIGN KEY(cliente_id) REFERENCES clientes(id) ON DELETE RESTRICT,
 INDEX(marca,modelo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS refacciones (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(120) NOT NULL,
 descripcion VARCHAR(500) NOT NULL DEFAULT '', proveedor VARCHAR(120) NOT NULL DEFAULT '',
 existencia INT NOT NULL DEFAULT 0 CHECK(existencia>=0),
 precio_centavos BIGINT NOT NULL CHECK(precio_centavos>=0), activo TINYINT(1) NOT NULL DEFAULT 1,
 INDEX(nombre)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ordenes_servicio (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cliente_id INT UNSIGNED NOT NULL,
 vehiculo_id INT UNSIGNED NOT NULL, mecanico_id INT UNSIGNED NOT NULL,
 falla TEXT NOT NULL, diagnostico TEXT NOT NULL, reparaciones TEXT NOT NULL,
 mano_obra_centavos BIGINT NOT NULL DEFAULT 0 CHECK(mano_obra_centavos>=0),
 estado ENUM('RECIBIDO','EN DIAGNÓSTICO','EN REPARACIÓN','LISTO PARA ENTREGAR','ENTREGADO') NOT NULL DEFAULT 'RECIBIDO',
 fecha_ingreso DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, fecha_entrega DATETIME NULL,
 creado_por INT UNSIGNED NOT NULL,
 FOREIGN KEY(cliente_id) REFERENCES clientes(id) ON DELETE RESTRICT,
 FOREIGN KEY(vehiculo_id) REFERENCES vehiculos(id) ON DELETE RESTRICT,
 FOREIGN KEY(mecanico_id) REFERENCES usuarios(id) ON DELETE RESTRICT,
 FOREIGN KEY(creado_por) REFERENCES usuarios(id) ON DELETE RESTRICT,
 INDEX(estado,fecha_ingreso), INDEX(fecha_entrega)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS detalles_orden (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, orden_id INT UNSIGNED NOT NULL, refaccion_id INT UNSIGNED NOT NULL,
 nombre_historico VARCHAR(120) NOT NULL, cantidad INT NOT NULL CHECK(cantidad>0),
 precio_centavos BIGINT NOT NULL CHECK(precio_centavos>=0), creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 operacion VARCHAR(64) NOT NULL UNIQUE,
 FOREIGN KEY(orden_id) REFERENCES ordenes_servicio(id) ON DELETE RESTRICT,
 FOREIGN KEY(refaccion_id) REFERENCES refacciones(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS movimientos_inventario (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, refaccion_id INT UNSIGNED NOT NULL,
 tipo ENUM('ENTRADA','SALIDA POR ORDEN') NOT NULL, cantidad INT NOT NULL CHECK(cantidad>0),
 usuario_id INT UNSIGNED NOT NULL, orden_id INT UNSIGNED NULL, detalle_id INT UNSIGNED NULL UNIQUE,
 motivo VARCHAR(250) NOT NULL, operacion VARCHAR(64) NOT NULL UNIQUE,
 creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(refaccion_id) REFERENCES refacciones(id) ON DELETE RESTRICT,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE RESTRICT,
 FOREIGN KEY(orden_id) REFERENCES ordenes_servicio(id) ON DELETE RESTRICT,
 FOREIGN KEY(detalle_id) REFERENCES detalles_orden(id) ON DELETE RESTRICT,
 INDEX(creado_en)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS pagos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, orden_id INT UNSIGNED NOT NULL,
 monto_centavos BIGINT NOT NULL CHECK(monto_centavos>0),
 metodo ENUM('Efectivo','Transferencia','Tarjeta') NOT NULL,
 usuario_id INT UNSIGNED NOT NULL, operacion VARCHAR(64) NOT NULL UNIQUE,
 creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(orden_id) REFERENCES ordenes_servicio(id) ON DELETE RESTRICT,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE RESTRICT,
 INDEX(creado_en)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS auditoria (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, usuario_id INT UNSIGNED NOT NULL,
 entidad VARCHAR(40) NOT NULL, registro_id INT UNSIGNED NOT NULL, accion VARCHAR(250) NOT NULL,
 creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE RESTRICT,
 INDEX(entidad,registro_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS intentos_acceso (
 identificador CHAR(64) PRIMARY KEY, intentos INT NOT NULL DEFAULT 0, ultimo DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
